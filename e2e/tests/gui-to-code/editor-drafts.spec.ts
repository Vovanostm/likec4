test('T03-b same-ID committed update shows a conflict and requires explicit reload', async ({ page }) => {
  await title(page).fill('Черновик пользователя')
  await page.getByRole('button', { name: 'Код', exact: true }).click()
  const source = page.getByLabel('Исходный код LikeC4')
  const before = await source.inputValue()
  expect(before).toContain('Web application')
  await source.fill(before.replace('Web application', 'Внешнее название'))
  await openPanel(page, 'Структура')
  await expect(page.getByRole('button', { name: /Внешнее название.*shop\.web/ })).toBeVisible()
  await openPanel(page, 'Инспектор')
  await expect(title(page)).toHaveValue('Черновик пользователя')
  await expect(inspector(page).getByRole('region', { name: 'Конфликт изменений' })).toBeVisible()
  await expect(inspector(page).getByRole('button', { name: 'Сохранить свойства' })).toBeDisabled()
  page.once('dialog', dialog => dialog.dismiss())
  await inspector(page).getByRole('button', { name: 'Загрузить актуальные значения' }).click()
  await expect(title(page)).toHaveValue('Черновик пользователя')
  page.once('dialog', dialog => dialog.accept())
  await inspector(page).getByRole('button', { name: 'Загрузить актуальные значения' }).click()
  await expect(title(page)).toHaveValue('Внешнее название')
  await expect(inspector(page).getByRole('region', { name: 'Конфликт изменений' })).toHaveCount(0)
})

test('T03-c confirmed save synchronizes normalized inputs and exact Undo/Redo source', async ({ page }) => {
  await page.getByRole('button', { name: 'Код', exact: true }).click()
  const source = page.getByLabel('Исходный код LikeC4')
  const before = await source.inputValue()
  await openPanel(page, 'Инспектор')
  await title(page).fill('  Подтверждённое название  ')
  await inspector(page).getByRole('button', { name: 'Сохранить свойства' }).click()
  await expect(title(page)).toHaveValue('Подтверждённое название')
  await expect(inspector(page).getByRole('status')).toHaveCount(0)
  const saved = await source.inputValue()
  expect(saved).not.toBe(before)
  await page.getByRole('button', { name: 'Отменить последнее изменение' }).click()
  await expect(title(page)).toHaveValue('Web application')
  await expect(source).toHaveValue(before)
  await page.getByRole('button', { name: 'Повторить отменённое изменение' }).click()
  await expect(title(page)).toHaveValue('Подтверждённое название')
  await expect(source).toHaveValue(saved)
})

for (const route of ['keyboard', 'quick action'] as const) {
  test(`hidden dirty Inspector guards canvas ${route} removal: Stay preserves, discard opens confirmation`, async ({ page }) => {
    await title(page).fill('Черновик перед удалением')
    await expect(inspector(page).getByRole('button', { name: 'Удалить элемент' })).toBeDisabled()
    const source = page.getByLabel('Исходный код LikeC4')
    const before = await source.inputValue()
    const removal = page.getByRole('dialog', { name: 'Удалить элемент?' })

    await requestCanvasRemoval(page, route)
    await expect(draftDialog(page)).toBeVisible()
    await expect(removal).toBeHidden()
    await expect(source).toHaveValue(before)
    await expect(draftDialog(page).getByRole('button', { name: 'Сохранить и перейти' })).toBeEnabled()
    await expect(draftDialog(page).getByRole('button', { name: 'Отбросить и перейти' })).toBeEnabled()
    await draftDialog(page).getByRole('button', { name: 'Остаться', exact: true }).click()
    await expect(draftDialog(page)).toBeHidden()
    await expect(removal).toBeHidden()
    await openPanel(page, 'Инспектор')
    await expect(title(page)).toHaveValue('Черновик перед удалением')
    await expect(source).toHaveValue(before)
    await expect(page.locator('.react-flow__node[data-id="shop.web"]')).toBeVisible()

    await requestCanvasRemoval(page, route)
    await expect(draftDialog(page)).toBeVisible()
    await expect(removal).toBeHidden()
    await draftDialog(page).getByRole('button', { name: 'Отбросить и перейти' }).click()
    await expect(draftDialog(page)).toBeHidden()
    await expect(removal).toBeVisible()
    await expect(removal).toHaveAttribute('data-removal-target', 'shop.web')
    await expect(source).toHaveValue(before)
    await removal.getByRole('button', { name: 'Отмена', exact: true }).click()
    await expect(removal).toBeHidden()
    await openPanel(page, 'Инспектор')
    await expect(title(page)).toHaveValue('Web application')
    await expect(source).toHaveValue(before)
  })

  test(`hidden dirty Inspector saves renamed identity before canvas ${route} removal`, async ({ page }) => {
    await inspector(page).getByText('Подробности', { exact: true }).click()
    await inspector(page).getByLabel('Локальный ID').fill('client_guard')
    const source = page.getByLabel('Исходный код LikeC4')
    const before = await source.inputValue()
    const removal = page.getByRole('dialog', { name: 'Удалить элемент?' })

    await requestCanvasRemoval(page, route)
    await expect(draftDialog(page)).toBeVisible()
    await expect(removal).toBeHidden()
    await expect(source).toHaveValue(before)
    await draftDialog(page).getByRole('button', { name: 'Сохранить и перейти' }).click()
    await expect(draftDialog(page)).toBeHidden()
    await expect(removal).toBeVisible()
    // The pending callback must read the current selection after the rename commit.
    await expect(removal).toHaveAttribute('data-removal-target', 'shop.client_guard')
    await expect(source).toHaveValue(/client_guard = component/)
    await expect(source).toHaveValue(/shop\.client_guard -> customer/)
    await expect(source).not.toHaveValue(/shop\.web/)
    const renamed = await source.inputValue()
    await removal.getByRole('button', { name: 'Удалить', exact: true }).click()
    await expect(removal).toBeHidden()
    await expect(source).not.toHaveValue(/\bclient_guard\b/)
    await expect(page.locator('.react-flow__node[data-id="shop.client_guard"]')).toHaveCount(0)
    const removed = await source.inputValue()
    const undo = page.getByRole('button', { name: 'Отменить последнее изменение' })
    await undo.click()
    await expect(source).toHaveValue(renamed)
    await undo.click()
    await expect(source).toHaveValue(before)
    const redo = page.getByRole('button', { name: 'Повторить отменённое изменение' })
    await redo.click()
    await expect(source).toHaveValue(renamed)
    await redo.click()
    await expect(source).toHaveValue(removed)
  })
}
