test('T03-b Stay prevents creation before mutation; discard releases one keyboard creation', async ({ page }) => {
  await page.getByRole('button', { name: 'Код', exact: true }).click()
  const source = page.getByLabel('Исходный код LikeC4')
  const before = await source.inputValue()
  await openPanel(page, 'Структура')
  // Count semantic tree entries even when the dirty-draft modal hides their panel.
  // Navigation still opens Structure explicitly; this is not a visibility assertion.
  const tree = page.getByRole('treeitem', { includeHidden: true })
  const beforeCount = await tree.count()
  const canvas = page.getByRole('region', { name: 'Холст диаграммы' })
  await expect(page.locator('.react-flow__pane').first()).toBeVisible()
  await openPanel(page, 'Инспектор')
  await title(page).fill('Черновик перед созданием')

  await canvas.focus()
  await page.keyboard.press('1')
  await page.keyboard.press('Enter')
  await expect(draftDialog(page)).toBeVisible()
  await expect(source).toHaveValue(before)
  await expect(tree).toHaveCount(beforeCount)
  await draftDialog(page).getByRole('button', { name: 'Остаться', exact: true }).click()
  await expect(draftDialog(page)).toBeHidden()
  await expect(title(page)).toHaveValue('Черновик перед созданием')
  await openPanel(page, 'Структура')
  await expect(web(page)).toHaveAttribute('aria-current', 'true')
  await expect(source).toHaveValue(before)
  await expect(tree).toHaveCount(beforeCount)

  await canvas.focus()
  await page.keyboard.press('1')
  await page.keyboard.press('Enter')
  await expect(draftDialog(page)).toBeVisible()
  await draftDialog(page).getByRole('button', { name: 'Отбросить и перейти' }).click()
  await expect(draftDialog(page)).toBeHidden()
  await expect(tree).toHaveCount(beforeCount + 1)
  await expect(source).not.toHaveValue(before)
  await expect(source).not.toHaveValue(/Черновик перед созданием/)
  const inlineTitle = page.getByRole('textbox', { name: 'Название элемента на холсте' })
  await expect(inlineTitle).toBeVisible()
  await inlineTitle.press('Escape')
  await openPanel(page, 'Структура')
  await expect(web(page)).not.toHaveAttribute('aria-current', 'true')
  await openPanel(page, 'Инспектор')
  await expect(title(page)).not.toHaveValue('Черновик перед созданием')
  await page.getByRole('button', { name: 'Отменить последнее изменение' }).click()
  await expect(source).toHaveValue(before)
  await expect(tree).toHaveCount(beforeCount)
})

