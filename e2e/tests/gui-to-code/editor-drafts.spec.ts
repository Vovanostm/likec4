import { type Page, expect, test } from '@playwright/test'
import { openPanel } from './panels'

const web = (page: Page) => page.getByRole('button', { name: /Web application.*shop\.web/ })
const other = (page: Page) => page.getByRole('treeitem').filter({ hasText: 'customer' }).getByRole('button').first()
const inspector = (page: Page) => page.getByRole('region', { name: 'Инспектор элемента' })
const title = (page: Page) => inspector(page).getByLabel('Название', { exact: true })
const draftDialog = (page: Page) => page.getByRole('dialog', { name: 'Сохранить изменения элемента?' })

async function requestCanvasRemoval(page: Page, route: 'keyboard' | 'quick action'): Promise<void> {
  await openPanel(page, 'Код')
  await expect(inspector(page)).toBeHidden()
  const canvas = page.getByRole('region', { name: 'Холст диаграммы' })
  if (route === 'keyboard') {
    await canvas.focus()
    await canvas.press('Delete')
  } else {
    await page.getByRole('button', { name: 'Закрыть панель «Код LikeC4»' }).click()
    await page.locator('.react-flow__node[data-id="shop.web"]').click({ button: 'right' })
    const remove = page.getByRole('menu', { name: 'Действия выбранной сущности', exact: true })
      .getByRole('menuitem', { name: /Удалить/ })
    await expect(remove).toBeEnabled()
    await remove.click()
  }
}

