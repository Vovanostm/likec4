test('T03-a keeps title, description, tags and caret across unrelated panel renders', async ({ page }) => {
  await page.getByRole('button', { name: 'Код', exact: true }).click()
  const source = page.getByLabel('Исходный код LikeC4')
  await source.fill((await source.inputValue()).replace('element actor', 'tag ui\n  element actor'))
  await openPanel(page, 'Инспектор')
  await inspector(page).getByText('Подробности', { exact: true }).click()
  await expect(inspector(page).getByRole('checkbox', { name: '#ui' })).toBeVisible()
  await title(page).fill('Несохранённое название')
  await inspector(page).getByLabel('Описание', { exact: true }).fill('Несохранённое описание')
  await inspector(page).getByRole('checkbox', { name: '#ui' }).check()
  const tags = await inspector(page).getByRole('checkbox').evaluateAll(inputs =>
    inputs.map(input => {
      return { name: input.parentElement?.textContent, checked: (input as HTMLInputElement).checked }
    })
  )
  await title(page).focus()
  await title(page).press('Home')
  await title(page).press('ArrowRight')
  const caret = await title(page).evaluate(input => (input as HTMLInputElement).selectionStart)
  await page.getByRole('button', { name: 'Структура', exact: true }).click()
  await expect(inspector(page)).toBeHidden()
  await openPanel(page, 'Инспектор')
  await expect(title(page)).toHaveValue('Несохранённое название')
  expect(await title(page).evaluate(input => (input as HTMLInputElement).selectionStart)).toBe(caret)
  await openPanel(page, 'Код')
  await expect(inspector(page)).toBeHidden()
  await openPanel(page, 'Инспектор')
  await expect(inspector(page).getByLabel('Описание', { exact: true })).toHaveValue('Несохранённое описание')
  expect(
    await inspector(page).getByRole('checkbox').evaluateAll(inputs =>
      inputs.map(input => {
        return { name: input.parentElement?.textContent, checked: (input as HTMLInputElement).checked }
      })
    ),
  ).toEqual(tags)
  await page.getByRole('button', { name: 'Инспектор', exact: true }).click()
  await expect(inspector(page)).toBeHidden()
  await page.getByRole('button', { name: 'Инспектор', exact: true }).click()
  await expect(title(page)).toHaveValue('Несохранённое название')
  await expect(inspector(page).getByLabel('Описание', { exact: true })).toHaveValue('Несохранённое описание')
  await expect(inspector(page).getByRole('checkbox', { name: '#ui' })).toBeChecked()
})

test('T03-b stay and Escape preserve the old selection; discard explicitly releases navigation', async ({ page }) => {
  await title(page).fill('Черновик')
  await openPanel(page, 'Структура')
  await other(page).click()
  await expect(draftDialog(page)).toBeVisible()
  await draftDialog(page).getByRole('button', { name: 'Остаться', exact: true }).click()
  await expect(draftDialog(page)).toBeHidden()
  await expect(title(page)).toHaveValue('Черновик')
  await expect(title(page)).toBeFocused()
  await openPanel(page, 'Структура')
  await other(page).click()
  await page.keyboard.press('Escape')
  await expect(draftDialog(page)).toBeHidden()
  await expect(title(page)).toHaveValue('Черновик')
  await expect(title(page)).toBeFocused()
  await openPanel(page, 'Структура')
  await other(page).click()
  await draftDialog(page).getByRole('button', { name: 'Отбросить и перейти' }).click()
  await expect(draftDialog(page)).toBeHidden()
  await openPanel(page, 'Инспектор')
  await expect(title(page)).not.toHaveValue('Черновик')
  await openPanel(page, 'Структура')
  await web(page).click()
  await openPanel(page, 'Инспектор')
  await expect(title(page)).toHaveValue('Web application')
})

